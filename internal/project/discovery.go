package project

import (
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"

	"odoo_method_analyzer/internal/model"
)

// Discover returns the customer source paths and the Odoo paths of the project at root.
// The Odoo paths are those of a single Odoo version: odooVersion when given (e.g. "200"), else the
// version the project runs on (odoo.conf, then .config.yml). Globbing every ../odoo* folder is the
// last resort: it mixes all the local Odoo versions, so a method removed in the target is still found.
func Discover(root string, odooVersion string) (model.ProjectPaths, error) {
	sourcePaths, extraPaths := projectAddonPaths(root)
	if len(sourcePaths) == 0 {
		return model.ProjectPaths{}, fmt.Errorf("no source addon paths found from %s", root)
	}

	var odooPaths []string
	if odooVersion != "" {
		odooPaths = versionOdooPaths(root, odooVersion, "")
		if len(odooPaths) == 0 {
			return model.ProjectPaths{}, fmt.Errorf("no Odoo sources found for version %s next to %s", odooVersion, root)
		}
	} else {
		odooPaths = odooConfPaths(root)
		if len(odooPaths) == 0 {
			version, hash := configVersion(root)
			if version != "" {
				odooPaths = versionOdooPaths(root, version, hash)
			}
		}
		if len(odooPaths) == 0 {
			if addonsOutput, err := getProjectData(root); err == nil && addonsOutput != "" && !looksLikeError(addonsOutput) {
				odooPaths = splitAddonPaths(root, addonsOutput).OdooPaths
			}
		}
		if len(odooPaths) == 0 {
			odooPaths = globOdooPaths(root)
		}
	}
	return model.ProjectPaths{
		SourcePaths: dedupeExisting(sourcePaths),
		OdooPaths:   dedupeExisting(append(odooPaths, extraPaths...)),
	}, nil
}

// projectAddonPaths returns the customer folders and the other addon folders of the project (extra...).
func projectAddonPaths(root string) ([]string, []string) {
	var sourcePaths []string
	var extraPaths []string
	for _, relative := range []string{"./code/modules/customer", "./code/modules/extra", "./modules/customer", "./modules/extra", "./addons"} {
		resolved := resolvePath(root, relative)
		if !isDir(resolved) {
			continue
		}
		if strings.HasSuffix(filepath.ToSlash(resolved), "/customer") {
			sourcePaths = append(sourcePaths, resolved)
		} else {
			extraPaths = append(extraPaths, resolved)
		}
	}
	return sourcePaths, extraPaths
}

// odooConfPaths returns the Odoo folders of the addons_path of odoo.conf (generated by init for the
// version of .config.yml), plus the server-wide addons (odoo/odoo/addons: base...) it does not list.
func odooConfPaths(root string) []string {
	for _, relative := range []string{"odoo.conf", "code/odoo.conf"} {
		content, err := os.ReadFile(resolvePath(root, relative))
		if err != nil {
			continue
		}
		for _, line := range strings.Split(string(content), "\n") {
			key, value, found := strings.Cut(line, "=")
			if !found || strings.TrimSpace(key) != "addons_path" {
				continue
			}
			var paths []string
			for _, rawPath := range strings.Split(value, ",") {
				path := resolvePath(root, strings.TrimSpace(rawPath))
				if strings.TrimSpace(rawPath) == "" || strings.HasPrefix(path, filepath.Clean(root)+string(filepath.Separator)) {
					continue
				}
				paths = append(paths, path)
				if strings.HasSuffix(filepath.ToSlash(path), "/odoo/addons") {
					paths = append(paths, filepath.Join(filepath.Dir(path), "odoo", "addons"))
				}
			}
			return paths
		}
	}
	return nil
}

// configVersion reads ODOO_VERSION and ODOO_HASH from .config.yml.
func configVersion(root string) (string, string) {
	var version, hash string
	for _, relative := range []string{".config.yml", "code/.config.yml"} {
		content, err := os.ReadFile(resolvePath(root, relative))
		if err != nil {
			continue
		}
		for _, line := range strings.Split(string(content), "\n") {
			key, value, found := strings.Cut(line, ":")
			if !found {
				continue
			}
			value = strings.Trim(strings.TrimSpace(value), "\"'")
			switch strings.TrimSpace(key) {
			case "ODOO_VERSION":
				version = value
			case "ODOO_HASH":
				hash = value
			}
		}
		break
	}
	return version, hash
}

// versionOdooPaths returns the Odoo folders of ../odoo_<version>: the worktree of hash when it exists,
// else the repository itself.
func versionOdooPaths(root string, version string, hash string) []string {
	repository := resolvePath(root, filepath.Join("..", "odoo_"+strings.ReplaceAll(version, ".", "")))
	base := repository
	if hash != "" && hash != "null" && isDir(filepath.Join(repository, ".worktree", hash)) {
		base = filepath.Join(repository, ".worktree", hash)
	}
	var paths []string
	for _, relative := range []string{"odoo/addons", "odoo/odoo/addons", "enterprise", "themes"} {
		if isDir(filepath.Join(base, relative)) {
			paths = append(paths, filepath.Join(base, relative))
		}
	}
	return paths
}

func getProjectData(root string) (string, error) {
	if _, err := exec.LookPath("get_project_data"); err != nil {
		return "", err
	}
	cmd := exec.Command("get_project_data", "-a")
	cmd.Dir = root
	output, err := cmd.CombinedOutput()
	if err != nil {
		return "", err
	}
	return strings.TrimSpace(string(output)), nil
}

func looksLikeError(output string) bool {
	lower := strings.ToLower(output)
	return strings.Contains(lower, "not found") || strings.Contains(lower, "error")
}

func splitAddonPaths(root string, output string) model.ProjectPaths {
	var sourcePaths []string
	var odooPaths []string
	for _, rawPath := range strings.Split(output, ",") {
		trimmed := strings.TrimSpace(rawPath)
		if trimmed == "" {
			continue
		}
		resolved := resolvePath(root, trimmed)
		if strings.HasSuffix(filepath.ToSlash(resolved), "/customer") {
			sourcePaths = append(sourcePaths, resolved)
		} else {
			odooPaths = append(odooPaths, resolved)
		}
	}
	return model.ProjectPaths{SourcePaths: dedupeExisting(sourcePaths), OdooPaths: dedupeExisting(odooPaths)}
}

// globOdooPaths is the last resort: every ../odoo* folder, whatever its version.
func globOdooPaths(root string) []string {
	var odooPaths []string
	for _, pattern := range []string{"../odoo*/odoo/addons", "../odoo*/addons", "./odoo/addons", "../odoo*/enterprise", "./enterprise", "../odoo*/themes", "./themes"} {
		matches, _ := filepath.Glob(filepath.Join(root, pattern))
		for _, match := range matches {
			if isDir(match) {
				odooPaths = append(odooPaths, filepath.Clean(match))
			}
		}
	}
	return odooPaths
}

func resolvePath(root string, path string) string {
	if filepath.IsAbs(path) {
		return filepath.Clean(path)
	}
	return filepath.Clean(filepath.Join(root, path))
}

func dedupeExisting(paths []string) []string {
	seen := make(map[string]struct{}, len(paths))
	result := make([]string, 0, len(paths))
	for _, path := range paths {
		cleanPath := filepath.Clean(path)
		if _, ok := seen[cleanPath]; ok || !isDir(cleanPath) {
			continue
		}
		seen[cleanPath] = struct{}{}
		result = append(result, cleanPath)
	}
	sort.Strings(result)
	return result
}

func isDir(path string) bool {
	info, err := os.Stat(path)
	return err == nil && info.IsDir()
}
